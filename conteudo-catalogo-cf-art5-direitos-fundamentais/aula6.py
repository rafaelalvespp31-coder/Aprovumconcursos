# ============================================================== 29 — Resumo final
sec("resumo", "Módulo 10 — Resumo de revisão da Parte I e próximos passos", """
**Conceitos essenciais**
- Direitos = bens protegidos; garantias = instrumentos de proteção; remédios = espécie de garantia.
- Dimensões: 1ª liberdade (abstenção), 2ª igualdade (prestação), 3ª fraternidade (transindividual).
- Características: históricos, universais, **relativos**, irrenunciáveis, inalienáveis, imprescritíveis, indivisíveis.
- Eficácia **vertical** (Estado × indivíduo) e **horizontal** (entre particulares).

**Regras constitucionais e exceções**
- § 1º aplicação imediata ≠ eficácia plena · § 2º rol aberto · § 3º tratados = emenda (3/5, 2 turnos, cada Casa) · § 4º TPI.
- Cláusula pétrea: veda emenda **tendente a abolir**.
- Casa: 24h para flagrante, desastre e socorro; ordem judicial **só de dia**; Tema 280 exige fundadas razões.
- Interceptação: **só juiz**, nas hipóteses da lei, para fins **penais**.
- Reunião: **aviso**, nunca autorização. Associação: suspensão por decisão judicial; dissolução por decisão judicial **transitada em julgado**.
- Desapropriação: prévia, justa, em dinheiro (salvo exceções). Requisição: ulterior, se houver dano.
- Racismo e grupos armados: **imprescritíveis**. 3TH: sem fiança, graça ou anistia.
- Penas vedadas: morte (salvo guerra declarada), perpétua, trabalhos forçados, banimento, cruéis.
- Extradição: nato **nunca**; naturalizado por crime comum anterior ou tráfico; estrangeiro, não por crime político ou de opinião.
- Presunção de inocência até o **trânsito em julgado** (ADCs 43, 44 e 54), com a exceção do júri (Tema 1.068).
- Prisão civil: só alimentos (SV 25).
- Gratuitos: HC e HD; registro de nascimento e certidão de óbito para os reconhecidamente pobres.

**Prazos e números**
- Comunicação da prisão: **imediata** (custódia em 24h).
- Quórum do § 3º: **3/5**, **dois turnos**.
- Associação para MS coletivo: **1 ano** de funcionamento.
- Justiça desportiva: **60 dias** para decidir.

**Legitimados e competência**
- Petição: qualquer pessoa, sem taxa e sem advogado.
- Ação penal privada subsidiária: ofendido, diante da **inércia** do MP.
- Extradição: julgada pelo **STF**.

**Próximos passos no APROVUM**
- **Parte II — Direitos sociais (arts. 6º a 11).**
- **Parte III — Nacionalidade, direitos políticos e partidos (arts. 12 a 17).**
- **Parte IV — Remédios constitucionais e tutela coletiva**, com o **simulado final** de 20 questões.
- Depois de ler, faça as questões dos três níveis (fácil, médio e difícil). A próxima etapa só libera com **90% de acerto** em cada nível.
""", N(62, 1, 13, 18, 28, 33, 37, 46, 57, 61))
