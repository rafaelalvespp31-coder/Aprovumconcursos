# ============================================================== 17 — Pegadinhas
sec("pegadinhas", "Módulo 10 — Pegadinhas recorrentes dos remédios constitucionais", """
- **"A ação civil pública é remédio constitucional do art. 5º."** Errado: está no art. 129, III.
- **"HC só cabe contra autoridade pública."** Errado: cabe contra particular.
- **"Pessoa jurídica pode ser paciente de HC."** Errado: só impetrante.
- **"HC exige advogado nos tribunais superiores."** Errado: dispensa sempre.
- **"Cabe HC para discutir condenação apenas à pena de multa."** Errado: Súmula 693.
- **"Cabe HC contra o mérito de punição disciplinar militar."** Errado: só os pressupostos de legalidade.
- **"MS cabe para proteger qualquer direito, inclusive locomoção."** Errado: é residual (não amparado por HC ou HD).
- **"Questão de direito complexa afasta o direito líquido e certo."** Errado: Súmula 625.
- **"O prazo do MS conta da prática do ato."** Errado: da ciência pelo interessado.
- **"Pedido de reconsideração interrompe o prazo do MS."** Errado: Súmula 430.
- **"Cabe MS contra lei em tese."** Errado: Súmula 266, salvo lei de efeitos concretos.
- **"MS serve para cobrar valores atrasados."** Errado: Súmulas 269 e 271.
- **"No MS há honorários de sucumbência."** Errado: Súmula 512.
- **"A lei proíbe liminar em MS sobre vantagens de servidores."** Superado: ADI 4.296.
- **"Partido sem representação no Congresso impetra MS coletivo."** Errado.
- **"Sindicato precisa de 1 ano de funcionamento para o MS coletivo."** Errado: requisito só da associação.
- **"MS coletivo exige autorização dos associados."** Errado: Súmula 629.
- **"MI cabe contra lei inconstitucional."** Errado: cabe contra omissão.
- **"Decisão de MI tem sempre efeito erga omnes."** Errado: regra inter partes.
- **"MI e ADO têm os mesmos legitimados."** Errado.
- **"HD dispensa pedido administrativo prévio."** Errado: Súmula 2 do STJ.
- **"HD serve para obter dados de terceiros ou informações públicas gerais."** Errado.
- **"HD dispensa advogado."** Errado: é gratuito, mas exige advogado.
- **"Negada a certidão, cabe HD."** Errado: mandado de segurança.
- **"Pessoa jurídica propõe ação popular."** Errado: Súmula 365.
- **"MP pode ajuizar ação popular."** Errado: acompanha e pode prosseguir.
- **"A ação popular exige prejuízo material."** Errado: Tema 836.
- **"Autor de ação popular derrotado paga custas."** Errado: só se comprovada má-fé.
- **"A ação popular contra o Presidente é julgada pelo STF."** Errado: primeiro grau.
- **"Improcedência por falta de prova faz coisa julgada erga omnes."** Errado.
- **"Gratuitas: HC, HD, MS e MI."** Errado: só HC e HD (LXXVII).
""", N(37, 2, 5, 7, 8, 9, 11, 13, 14, 16, 17, 20, 22, 24, 26, 27, 28, 30, 31, 32, 34))
