# ============================================================== 8 — Soberania popular
sec("explicacao", "Módulo 3 — Soberania popular: sufrágio, voto, plebiscito, referendo e iniciativa popular (art. 14, caput)", """
A soberania popular será exercida pelo **sufrágio universal** e pelo **voto direto e secreto**, **com valor igual para todos**, e, **nos termos da lei**, mediante: **I — plebiscito**; **II — referendo**; **III — iniciativa popular**.

Isso concretiza o parágrafo único do art. 1º: **todo o poder emana do povo**, que o exerce por meio de **representantes eleitos** (democracia **representativa**) **ou diretamente** (democracia **direta**) — por isso o Brasil adota a **democracia semidireta (participativa)**.

### Sufrágio × voto × escrutínio

| Conceito | O que é | Característica no Brasil |
|---|---|---|
| **Sufrágio** | O **direito** de votar e ser votado (essência dos direitos políticos) | **Universal** — não depende de renda (censitário) ou de capacidade especial (capacitário) |
| **Voto** | O **exercício** do sufrágio; o ato de votar | **Direto, secreto, igual** (e **periódico** — cláusula pétrea, art. 60, § 4º, II) |
| **Escrutínio** | O **modo/procedimento** de votação e apuração | Secreto, eletrônico |

📌 **Cláusula pétrea:** o art. 60, § 4º, II protege o **voto direto, secreto, universal e periódico**. **A obrigatoriedade do voto não é cláusula pétrea** — poderia, em tese, ser abolida por emenda.

📌 **Voto direto — exceção:** se vagarem os cargos de Presidente e Vice nos **dois últimos anos** do mandato, a eleição será **indireta**, pelo **Congresso Nacional**, em 30 dias (art. 81, § 1º).

### Plebiscito × referendo × iniciativa popular

| | **Plebiscito** | **Referendo** | **Iniciativa popular** |
|---|---|---|---|
| Momento | **Antes** do ato (consulta **prévia**) | **Depois** do ato (consulta **posterior**: ratifica ou rejeita) | O povo **propõe** o projeto |
| Quem convoca (âmbito nacional) | **Congresso Nacional**, por **decreto legislativo** (art. 49, XV) | **Congresso Nacional** **autoriza**, por decreto legislativo (art. 49, XV) | — |
| Exemplo | 1993 — forma (república) e sistema (presidencialismo) de governo | 2005 — proibição do comércio de armas de fogo (rejeitada) | Lei da Ficha Limpa (LC 135/2010) |
| Lei | Lei 9.709/1998 | Lei 9.709/1998 | art. 61, § 2º |

**Macete:** **PLE**biscito = **PRÉ**via · **REF**erendo = **REF**erenda (confirma depois).

**Iniciativa popular de lei federal (art. 61, § 2º):** projeto subscrito por, no mínimo, **1% do eleitorado nacional**, distribuído por **pelo menos cinco Estados**, com **não menos de 0,3%** dos eleitores de cada um deles.
- Nos **Municípios**: **5% do eleitorado** (art. 29, XIII).
- Nos **Estados**: a lei disporá (art. 27, § 4º).

⚠️ **Pegadinhas:**
- "No referendo, o povo é consultado antes da edição do ato." **Errado** — isso é **plebiscito**.
- "O voto obrigatório é cláusula pétrea." **Errado** — pétreos são o voto direto, secreto, universal e periódico.
- "Sufrágio e voto são sinônimos." **Errado** — sufrágio é o direito; voto, seu exercício.
""", N(19, 20, 21))
