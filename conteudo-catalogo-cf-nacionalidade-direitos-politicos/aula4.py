# ============================================================== 20 — Pegadinhas
sec("pegadinhas", "Módulo 6 — Pegadinhas recorrentes dos arts. 12 a 17", """
- **"Todo nascido no Brasil é brasileiro nato."** Errado: salvo filhos de pais estrangeiros a serviço de **seu** país.
- **"Na alínea b, os dois pais devem ser brasileiros."** Errado: pai **ou** mãe, desde que **qualquer deles** esteja a serviço do Brasil.
- **"A opção pela nacionalidade deve ocorrer até os 21 anos."** Errado: em **qualquer tempo**, após a maioridade.
- **"Lusófonos precisam de 4 anos de residência."** Errado: **1 ano ininterrupto** + idoneidade moral.
- **"Naturalização extraordinária exige mais de 10 anos."** Errado: **mais de 15 anos** ininterruptos, sem condenação penal.
- **"O português equiparado é naturalizado."** Errado: continua português, com direitos de brasileiro.
- **"Lei pode criar distinções entre natos e naturalizados."** Errado: só a **Constituição**.
- **"Ministro do STJ e senador são cargos privativos de nato."** Errado.
- **"Ministro da Defesa pode ser naturalizado."** Errado: privativo de nato (EC 23/1999).
- **"Perde a nacionalidade quem adquire outra."** Errado após a **EC 131/2023**.
- **"Quem renunciou à nacionalidade não pode readquiri-la."** Errado: § 5º.
- **"Símbolos: bandeira, hino, armas e moeda."** Errado: **selo**.
- **"Referendo é consulta prévia."** Errado: é **posterior**.
- **"O voto obrigatório é cláusula pétrea."** Errado.
- **"Voto facultativo para maiores de 65."** Errado: **70**.
- **"Conscrito pode se alistar."** Errado.
- **"Analfabeto não vota."** Errado: vota facultativamente; não pode ser votado.
- **"Senador: 30 anos."** Errado: **35**.
- **"Prefeito: 25 anos."** Errado: **21**.
- **"Existe candidatura avulsa."** Errado: filiação é condição de elegibilidade.
- **"Para se reeleger, o Presidente deve renunciar 6 meses antes."** Errado: só para **outros** cargos.
- **"Parlamentares só podem ser reeleitos uma vez."** Errado: sem limite.
- **"Inelegibilidade reflexa alcança parentes de parlamentares."** Errado: só de **chefes do Executivo**.
- **"Divórcio no curso do mandato afasta a inelegibilidade."** Errado: SV 18.
- **"Lei ordinária pode criar inelegibilidades."** Errado: **lei complementar**.
- **"AIME: 15 dias da eleição."** Errado: da **diplomação**.
- **"A Constituição admite cassação de direitos políticos."** Errado: é **vedada**.
- **"Inelegível não vota."** Errado: inelegibilidade afeta só a capacidade **passiva**.
- **"A suspensão por condenação exige reabilitação para cessar."** Errado: Súmula 9 do TSE.
- **"Lei eleitoral só entra em vigor um ano depois."** Errado: vige na publicação; não se aplica à eleição em até um ano.
- **"Partido é pessoa jurídica de direito público."** Errado: direito privado.
- **"Coligação para vereador é permitida."** Errado.
- **"Partido sem cláusula de desempenho é extinto."** Errado: perde fundo e tempo de TV.
- **"Senador que troca de partido perde o mandato."** Errado: ADI 5.081.
""", N(44, 6, 7, 8, 10, 11, 12, 14, 15, 17, 18, 21, 22, 24, 26, 27, 29, 31, 32, 34, 35, 37, 38, 39, 40, 42))
