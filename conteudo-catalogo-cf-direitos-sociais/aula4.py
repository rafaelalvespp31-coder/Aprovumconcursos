# ============================================================== 19 — Pegadinhas
sec("pegadinhas", "Módulo 8 — Pegadinhas recorrentes dos direitos sociais", """
- **"Direitos sociais são normas programáticas sem valor jurídico."** Errado: têm força normativa e podem ser exigidos judicialmente nas condições da jurisprudência.
- **"A reserva do possível autoriza o Estado a negar qualquer prestação alegando falta de verba."** Errado: exige comprovação concreta e cede ao mínimo existencial.
- **"Meio ambiente está no rol do art. 6º."** Errado: está no art. 225.
- **"O transporte é direito social desde 1988."** Errado: incluído pela EC 90/2015.
- **"A renda básica familiar é devida a todos os brasileiros."** Errado: aos brasileiros em situação de vulnerabilidade social, nos termos da lei.
- **"A proteção contra despedida arbitrária depende de lei ordinária."** Errado: lei complementar.
- **"O salário mínimo pode ser fixado pelos Estados."** Errado: é nacionalmente unificado; Estados podem fixar **piso** por delegação.
- **"O salário mínimo pode servir de indexador de vantagens."** Errado: vedada a vinculação (SV 4).
- **"O salário é irredutível em qualquer hipótese."** Errado: salvo convenção ou acordo coletivo.
- **"A jornada é de 8h diárias e 48h semanais."** Errado: 44h.
- **"Repouso semanal obrigatoriamente aos domingos."** Errado: preferencialmente.
- **"Hora extra com exatamente 50%."** Errado: no mínimo 50%.
- **"Licença à gestante de 180 dias pela CF."** Errado: 120 dias.
- **"Creche até 6 anos."** Errado: até 5 anos (EC 53/2006).
- **"O seguro de acidente exclui a indenização do empregador."** Errado: não exclui, em caso de dolo ou culpa.
- **"Prescrição de 2 anos contados de cada lesão."** Errado: 5 anos, até 2 anos após a extinção do contrato.
- **"O menor de 16 pode trabalhar em atividade leve."** Errado: só aprendiz a partir de 14.
- **"Os domésticos têm todos os direitos do art. 7º."** Errado: extensão seletiva.
- **"A base territorial mínima do sindicato é o Estado."** Errado: Município.
- **"A base territorial é definida pelo Ministério do Trabalho."** Errado: pelos interessados.
- **"A contribuição confederativa é obrigatória para toda a categoria."** Errado: só filiados (SV 40).
- **"A estabilidade do dirigente começa com a posse e não alcança o suplente."** Errado: começa com o registro da candidatura e alcança o suplente.
- **"O aposentado não pode votar no sindicato."** Errado: o aposentado filiado vota e é votado.
- **"Policiais civis podem fazer greve se mantiverem os serviços essenciais."** Errado: Tema 541.
- **"A greve do servidor depende de lei complementar."** Errado: lei específica.
- **"Empresas com 200 ou mais empregados elegem representante."** Errado: mais de 200.
""", N(40, 2, 4, 7, 8, 10, 13, 14, 15, 16, 17, 18, 19, 21, 23, 26, 28, 29, 35, 38))
