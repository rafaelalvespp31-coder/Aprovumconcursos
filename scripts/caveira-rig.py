m = Image.new("L", (src.width * 4, src.height * 4), 0)
dr = ImageDraw.Draw(m)
for poly in P.values():
    dr.polygon([(x * 4, y * 4) for x, y in poly], fill=255)
m = m.filter(ImageFilter.MaxFilter(9)).resize(src.size, Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.7))
